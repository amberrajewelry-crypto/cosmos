const ORB_T = 3;

export interface TimeHit { head: string; text: string; point: string; orb: number; kind: Kind; }
export function transitReading(natal: Row[], now: Row[], asc?: number): TimeHit[] {
  const targets: Row[] = natal.filter((r) => POINT[r.key]);
  if (asc != null) targets.push({ key: 'asc', glyph: 'ASC', name: 'Асцендент', lon: asc });
  const out: TimeHit[] = [];
  for (const t of now.filter((r) => TRANSIT[r.key])) for (const n of targets) {
    const diff = Math.abs(((t.lon - n.lon + 540) % 360) - 180);
    for (const asp of ASPECTS) {
      const orb = Math.abs(diff - asp.deg); if (orb > ORB_T) continue;
      const c = CASES[n.key]; const text = TRANSIT[t.key][kindOf(asp.kind)].replace('{pi}', c[1]).replace('{pa}', c[2]).replace('{pd}', c[3]).replace('{p}', c[0]);
      out.push({ head: `${t.glyph}︎ ${t.name} сейчас ${asp.glyph} ${n.glyph}︎ ${n.name} рождения`, text, point: `${asp.ru}, орбис ${orb.toFixed(1)}° · ${POINT[n.key]}`, orb, kind: kindOf(asp.kind) });
      break;
    }
  }
  return out.sort((a, b) => a.orb - b.orb).slice(0, 8);
}

