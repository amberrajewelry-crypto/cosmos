export function synastryReading(a: Row[], b: Row[]): TimeHit[] {
  const keys = ['sun', 'moon', 'venus', 'mars', 'saturn'];
  const out: TimeHit[] = [];
  for (const ka of keys) for (const kb of keys) {
    const pa = a.find((r) => r.key === ka)!, pb = b.find((r) => r.key === kb)!;
    const pairKey = keys.indexOf(ka) <= keys.indexOf(kb) ? `${ka}-${kb}` : `${kb}-${ka}`;
    const diff = Math.abs(((pa.lon - pb.lon + 540) % 360) - 180);
    for (const asp of ASPECTS) {
      const orb = Math.abs(diff - asp.deg); if (orb > Math.min(asp.orb, 5)) continue;
      const k = kindOf(asp.kind); const text = `${SYN[pairKey][k === 'c' ? 'h' : k]} Наставление: ${SYN[pairKey].a}`;
      out.push({ head: `${pa.glyph}︎ ${pa.name} A ${asp.glyph} ${pb.glyph}︎ ${pb.name} B`, text, point: `${asp.ru}, орбис ${orb.toFixed(1)}°`, orb, kind: k });
      break;
    }
  }
  return out.sort((x, y) => x.orb - y.orb).slice(0, 10);
}

