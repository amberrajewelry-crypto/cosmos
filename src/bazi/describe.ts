function topGroup(weights: number[]): number {
  let best = 0;
  for (let i = 1; i < 5; i++) if (weights[i] > weights[best]) best = i;
  return best;
}

export function powerType(c: Chart, a: Analysis): PowerType {
  const f = a.brain.frame.kind;
  if (f === 'vibrant') return 'vibrant';
  if (f === 'follow') return 'follow';
  if (f === 'transform') return 'transform';
  const d = a.dmEl, P = c.pillars;
  const res = ((d + 4) % 5) as El, out = ((d + 1) % 5) as El, wealth = ((d + 2) % 5) as El, officer = ((d + 3) % 5) as El;
  // «работает» = заметная доля и стоит на виду (ствол) или главной ци ветви — не только спрятанный остаток (KB 18 §1).
  const shown = (e: El) => P.some((p) => (p.pos !== 'day' && STEMS[p.stem].el === e) || STEMS[BRANCHES[p.branch].hidden[0]].el === e);
  const works = (e: El) => a.pct[e] >= 0.12 && shown(e);
  const k = a.brain.power.key;
  if (k === 'strong') {
    const check = a.pct[out] + a.pct[wealth] + a.pct[officer];
    return check >= 0.3 && [out, wealth, officer].some(works) ? 'strong-check' : 'strong-free';
  }
  if (k === 'weak') {
    const tot = a.scores.reduce((s, x) => s + x, 0) || 1;
    const help = (a.scores[res] + a.scores[d]) / tot;
    const ownShown = P.some((p) => p.pos !== 'day' && STEMS[p.stem].el === d) || P.some((p) => STEMS[BRANCHES[p.branch].hidden[0]].el === d);
    return help >= 0.25 && (works(res) || ownShown) ? 'weak-support' : 'weak-alone';
  }
  return 'balanced';
}

export function describe(c: Chart, a: Analysis): Description {
  const d = a.dmEl, P = c.pillars, lines: string[] = [], detail: string[] = [];
  const type = powerType(c, a);

  // §1 тип
  lines.push(type === 'vibrant' ? VIBRANT_TEXT[d] : TYPE_TEXT[type]);
  detail.push(`Тип по силе и сдержке: ${a.brain.power.ru}, ${{ 'strong-check': 'есть рабочая сдержка (Выражение/Богатство/Власть на виду)', 'strong-free': 'сдержки на виду нет', 'weak-support': 'есть опора (Ресурс или своя стихия на виду)', 'weak-alone': 'опоры на виду нет', balanced: 'на равновесии', vibrant: 'одна стихия (专旺)', follow: 'следование (从)', transform: 'превращение (化)' }[type]} — СМ т.7 論性情相貌, ЦЛ 性情.`);

  // §0 облик: перекос (ДТС «浊乱偏枯，性情乖逆») — только для обычных карт
  const maxP = Math.max(...a.pct), missing = a.pct.filter((x) => x < 0.04).length;
  if (!['vibrant', 'follow', 'transform'].includes(type) && (maxP >= 0.45 || missing >= 2)) {
    // при «равновесии» силы не писать рядом «крайностей мало» и «с крайностями» — одна фраза про оба слоя
    if (type === 'balanced') lines[0] = 'Сила в равновесии, но стихии в карте распределены неровно: характер с крайностями, и от одного периода жизни к другому вы заметно меняетесь.';
    else lines.push('Карта с сильным перекосом: характер яркий, с крайностями — середина даётся вам труднее, чем другим.');
    detail.push(`Облик: перекос (макс. доля ${Math.round(maxP * 100)}%, почти нет ${missing} стихий) — ДТС 性情 «偏枯».`);
  }

  // §3 черта/тень полезного бога: из пары (инь/ян) берём того, кто сильнее в карте
  const y = a.brain.yong, r = rel(d, y);
  const pair = [['BJ', 'JC'], ['SS', 'SG'], ['ZC', 'PC'], ['ZG', 'QS'], ['ZY', 'PY']][r];
  const gk = (a.gods[pair[1]] ?? 0) > (a.gods[pair[0]] ?? 0) ? pair[1] : pair[0];
  const [plus, minus] = TRAIT[gk];
  // Тень — только при избытке («…太多», ЦЛ 性情): у дефицитного полезного бога тени нет, иначе портрет противоречит сам себе
  // (сильному с нужным, но скудным Богатством выпадала «мягкотелость»).
  const yPct = a.pct[y];
  lines.push(yPct >= 0.25 ? `Ваша сильная сторона — ${plus}. Обратная сторона — ${minus}.` : `Ваша сильная сторона — ${plus}. Она растёт, когда вы её упражняете.`);
  detail.push(`Черта/тень: полезный бог — ${GODS[gk].ru} (${GODS[gk].zh}), ЦЛ 性情 «…为用神 / …太多».`);

  // §2 точка срыва = «击神» Жэня (ДТС 性情): сильному мешает то, что запирает выход — Власть и Ресурс
  // («木旺得火以通之…不宜见金水之击»), слабому — то, что тянет силы, — Выражение и Богатство («木衰得水…不宜见火土之击»).
  // Своя стихия — не «击神». Берём только из вредных (если Власть — полезный бог, это не срыв).
  const pk = a.brain.power.key, cand = (pk === 'strong' ? [(d + 3) % 5, (d + 4) % 5] : pk === 'weak' ? [(d + 1) % 5, (d + 2) % 5] : [0, 1, 2, 3, 4].filter((e) => e !== d)) as El[];
  const ji = cand.filter((e) => a.brain.ji.includes(e)).sort((p, q) => a.pct[q] - a.pct[p])[0];
  if (ji !== undefined && a.pct[ji] >= 0.1) {
    const react = a.brain.power.key === 'strong' ? 'вы вспыхиваете и идёте напролом'
      : a.brain.power.key === 'weak' ? 'вы сжимаетесь и уступаете, а потом жалеете' : 'вы теряете ровность и делаете лишнее';
    lines.push(`Где вы теряете равновесие: ${TRIGGER[rel(d, ji)]} — тогда ${react}.`);
    detail.push(`Точка срыва: вредная стихия ${REL_GROUP[rel(d, ji)]} (${Math.round(a.pct[ji] * 100)}%) — ДТС 性情 «击神»: «旺者勇急，衰者懦弱».`);
  }

  // §5 снаружи / внутри
  const outerW = [0, 0, 0, 0, 0], innerW = [0, 0, 0, 0, 0];
  for (const p of P) {
    if (p.pos !== 'day') outerW[rel(d, STEMS[p.stem].el)] += p.pos === 'month' ? 1.5 : 1;
    innerW[rel(d, STEMS[BRANCHES[p.branch].hidden[0]].el)] += p.pos === 'day' ? 2 : p.pos === 'month' ? 1.5 : 1;
  }
  const og = topGroup(outerW), ig = topGroup(innerW);
  const fem = !c.input.male, outer = (fem ? OUTER_F : OUTER)[og];
  // «Маски нет» нельзя говорить, если облик спорит с типом из §1: сильный с мягким обликом (Печать) или слабый
  // с обликом «несговорчивый» (свои) — тогда облик описываем как то, что видят до давления / как защиту.
  const strongT = type === 'strong-check' || type === 'strong-free', weakT = type === 'weak-support' || type === 'weak-alone';
  const clashOuter = (strongT && og === 4) || (weakT && og === 0);
  lines.push(og === ig && !clashOuter ? `${fem ? 'Какой' : 'Каким'} вас видят — ${outer}, — ${fem ? 'такая' : 'такой'} вы и внутри: маски у вас нет.`
    : clashOuter && strongT ? `Со стороны вы кажетесь ${outer} — но это до первого давления: сил под этим больше, чем видно.`
    : clashOuter ? `Со стороны вы кажетесь ${outer} — это защита: так вы держите дистанцию, пока не уверены в людях.`
    : `Со стороны вы кажетесь ${outer}, а ${INNER[ig]}.`);
  detail.push(`Снаружи/внутри: стволы — ${REL_GROUP[og]}, главная ци ветвей — ${REL_GROUP[ig]} (盲派 гл.2: «天干代表人的表象…地支代表人的内在»).`);

  // 朱 (冲 у ветви дня с соседней ветвью): «内心动荡»
  const day = P.find((p) => p.pos === 'day')!;
  const near = P.filter((p) => p.pos === 'month' || p.pos === 'hour');
  if (near.some((p) => Math.abs(p.branch - day.branch) === 6)) {
    lines.push('Внутри часто неспокойно: тянет менять дом, работу, планы — это ваш способ двигаться, а не слабость.');
    detail.push('Удар по ветви дня от соседней ветви — 朱祖夏 (八字与用神, 冲): «内心动荡».');
  }
  // §6.6 нрав по тактам (МЛЮЯ «始正而终邪者…则行运使然耳»; Жэнь: «至岁运遇击神，亦能变为强弱»)
  const ph = phases(c, a);
  if (ph.length > 1) {
    const W = { strong: 'напористее и резче', weak: 'осторожнее и мягче', balanced: 'ровнее, без крайностей' };
    const seg = ph.map((x, i) => `${i === 0 ? `до ${ph[1].age} лет` : i === ph.length - 1 ? `после ${x.age}` : `с ${x.age} до ${ph[i + 1].age}`} — ${W[x.key]}`);
    lines.push(`С возрастом нрав меняется: ${seg.join('; ')}.`);
    detail.push(`По тактам сила дня меняет тип (ствол такта ±1, ветвь — корень по шкале ЦПЦЦ гл.3 или ±1): ${ph.map((x) => `${x.age}+ ${x.key}`).join(', ')} — МЛЮЯ 看性情法 «行运使然».`);
  }
  return { type, lines, detail };
}

/** Тип силы по тактам до 75 лет: натальная шкала brain + ствол и ветвь такта; соседние одинаковые склеены. */
export function phases(c: Chart, a: Analysis): { age: number; year: number; key: 'strong' | 'weak' | 'balanced' }[] {
  if (a.brain.frame.kind !== 'normal' || !c.luck?.length) return [];
  const d = a.dmEl, res = (d + 4) % 5, up = (e: number) => (e === d || e === res ? 1 : -1);
  type K = 'strong' | 'weak' | 'balanced';
  const per: { age: number; year: number; key: K }[] = [{ age: 0, year: c.luck[0].year - Math.round(c.luck[0].age), key: a.brain.power.key }];
  for (const l of c.luck) {
    if (l.age >= 75) break;
    const s = l.idx % 10, b = l.idx % 12, root = rootOf(a.dm, b)?.w ?? 0;
    const score = a.brain.power.score + up(STEMS[s].el) + (root ? root : up(STEMS[BRANCHES[b].hidden[0]].el));
    per.push({ age: Math.round(l.age), year: l.year, key: score >= 3 ? 'strong' : score <= -1 ? 'weak' : 'balanced' });
  }
  // сглаживание: сдвиг засчитываем, только если держится ≥ 2 такта (20 лет), иначе это фон, а не перемена нрава
  const out: typeof per = [per[0]];
  for (let i = 1; i < per.length; i++) {
    const cur = out[out.length - 1].key;
    if (per[i].key !== cur && per[i + 1]?.key === per[i].key) out.push(per[i]);
  }
  return out;
}

/** Для «Подробного разбора»: механизм описания с источниками. */
export function describeNote(c: Chart, a: Analysis): Note {
  return { title: 'Как построен портрет', text: describe(c, a).detail.join(' '), quote: '先看柱中神情气势…然后以五行推之', src: 'МЛЮЯ, 看性情法 (KB 18)' };
}
