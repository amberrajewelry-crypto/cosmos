import { describe, it, expect } from 'vitest';
import { plain, lay } from '../src/bazi/ui-kit';

describe('простые слова в основном потоке', () => {
  it('без иероглифов, книг и «столпа/силы на грани»', () => {
    const t = lay('Стихия периода — нагрузка. Сила на грани, период её опускает — здесь полезнее вода (朱祖夏 中和). Двойной удар по столпу дня (天克地冲): перемены в доме — «间有不利» (命理约言 太岁论).');
    expect(t).not.toMatch(/[㐀-鿿]|столп|на грани/);
    expect(t).toContain('Ваша карта в равновесии');
    expect(t).toContain('встряска в личной жизни');
  });
  it('сила на грани в месяце', () => {
    expect(plain('сила на грани: в этот период полезнее вода, а не земля')).toBe('в этот период вам полезнее вода, а не земля');
  });
});

import { teaser } from '../src/bazi/sharecard';
describe('текст для картинки', () => {
  it('целые предложения, не длиннее 150, первое — всегда', () => {
    const t = 'Стихия периода — нагрузка, по расчёту он тяжёлый целиком. Ваша карта в равновесии, и этот период её ослабляет — здесь полезнее вода. Сильная встряска в личной жизни: перемены в доме, паре, здоровье.';
    const r = teaser(t);
    expect(r.length).toBeLessThanOrEqual(150); expect(r.endsWith('.')).toBe(true); expect(r.startsWith('Стихия')).toBe(true);
    expect(teaser('Очень длинное первое предложение без точки до самого конца')).toContain('Очень');
  });
});
